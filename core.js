export function isComplete(answer) {
 return !!answer && Number.isInteger(answer.first) && Number.isInteger(answer.second) && answer.first >= 0 && answer.first < 4 && answer.second >= 0 && answer.second < 4 && answer.first !== answer.second;
}
export function calculateScores(answers) {
 if (answers.length !== 12 || !answers.every(isComplete)) throw new Error('12問すべてで異なる2つの選択肢を選んでください。');
 const scores = [0,0,0,0];
 for (const answer of answers) { scores[answer.first] += 2; scores[answer.second] += 1; }
 return scores;
}
export function leadingIndices(scores) {
 const max = Math.max(...scores);
 return scores.map((s,i) => s === max ? i : -1).filter(i => i !== -1);
}
